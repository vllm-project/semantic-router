"""The Supported models pages follow the built-in catalog and fail closed on drift."""

from __future__ import annotations

import importlib.util
import json
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
SPEC = importlib.util.spec_from_file_location(
    "generate_model_pages", ROOT / "tools/docs/generate_model_pages.py"
)
pages = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = pages
SPEC.loader.exec_module(pages)


class ModelPagesTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        self.saved = {
            name: getattr(pages, name) for name in ("PAGES", "ZH_PAGES", "EDITORIAL")
        }
        self.addCleanup(lambda: [setattr(pages, k, v) for k, v in self.saved.items()])

    def use_copies(self):
        """Point the generator at copies of the pages and the editorial file."""
        pages.PAGES = self.root / "en"
        pages.ZH_PAGES = self.root / "zh"
        shutil.copytree(self.saved["PAGES"], pages.PAGES)
        if self.saved["ZH_PAGES"].is_dir():
            shutil.copytree(self.saved["ZH_PAGES"], pages.ZH_PAGES)
        pages.EDITORIAL = self.root / "supported_models.yaml"
        shutil.copyfile(self.saved["EDITORIAL"], pages.EDITORIAL)

    def test_committed_pages_are_current(self):
        self.assertEqual(pages.main(["--check"]), 0)

    def test_every_catalog_model_has_a_page_with_its_pin(self):
        catalog = json.loads(pages.CATALOG.read_text())["models"]
        models = {model.repo: model for model in pages.load_models()}
        self.assertEqual(set(models), {item["id"] for item in catalog})
        for repo, model in models.items():
            with self.subTest(repo=repo):
                path = pages.PAGES / model.family_dir / f"{model.page}.md"
                text = path.read_text()
                self.assertIn(f"[`{repo}`](https://huggingface.co/{repo})", text)
                self.assertIn(model.revision[:12], text)
                self.assertIn(f"vllm-sr serve {repo} --engine", text)

    def test_span_capability_decides_the_deployment_snippet(self):
        for model in pages.load_models():
            with self.subTest(repo=model.repo):
                text = pages.render_page(model)
                self.assertEqual(
                    "pii: spans" in text, "span" not in model.question_types
                )

    def test_a_catalog_model_without_editorial_text_fails(self):
        self.use_copies()
        editorial = yaml.safe_load(pages.EDITORIAL.read_text())
        editorial["models"].pop("vllm-sr/vela3-fast")
        pages.EDITORIAL.write_text(yaml.safe_dump(editorial))
        with self.assertRaisesRegex(SystemExit, "no entry for vllm-sr/vela3-fast"):
            pages.load_models()

    def test_a_missing_record_fails(self):
        self.use_copies()
        editorial = yaml.safe_load(pages.EDITORIAL.read_text())
        editorial["models"]["vllm-sr/d3"]["records"] = ["no-such-record.md"]
        pages.EDITORIAL.write_text(yaml.safe_dump(editorial))
        with self.assertRaisesRegex(SystemExit, "no-such-record.md does not exist"):
            pages.load_models()

    def test_check_reports_an_edited_or_orphaned_page(self):
        self.use_copies()
        page = pages.PAGES / "decision-3" / "d3.md"
        page.write_text(page.read_text() + "\nEdited by hand.\n")
        self.assertEqual(pages.main(["--check"]), 1)
        self.assertEqual(pages.main([]), 0)
        self.assertEqual(pages.main(["--check"]), 0)
        orphan = pages.PAGES / "decision-3" / "d3-retired.md"
        orphan.write_text(f"<!-- Generated by {pages.GENERATED_BY} -->\n")
        self.assertEqual(pages.main(["--check"]), 1)
        self.assertEqual(pages.main([]), 0)
        self.assertFalse(orphan.exists())


if __name__ == "__main__":
    unittest.main()
