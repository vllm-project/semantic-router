// Package websearch holds what web-search providers and page fetchers share.
// Provider-specific clients live in subpackages such as duckduckgo.
package websearch

import "math/rand"

// DefaultUserAgents returns a copy of the browser user agents that scrapers
// rotate through to look like ordinary browser traffic.
func DefaultUserAgents() []string {
	return append([]string(nil), defaultUserAgents...)
}

// RandomUserAgent returns one of the default browser user agents.
func RandomUserAgent() string {
	return defaultUserAgents[rand.Intn(len(defaultUserAgents))]
}

