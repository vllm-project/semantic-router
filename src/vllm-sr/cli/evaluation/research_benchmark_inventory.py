"""Load the canonical, package-safe inventory of audited research benchmarks.

The manifest ships with ``cli.evaluation``. The Go control plane embeds a
generated byte-for-byte mirror owned by
``tools/ci/sync_evaluation_catalogs.py``. It is about readiness, source parity,
and evidence ceilings; it never asserts native runs.
"""

from __future__ import annotations

from collections.abc import Mapping
from importlib.resources import files
from types import MappingProxyType
from typing import Any

from cli.evaluation.benchmark_registry import get_benchmark_registry
from cli.evaluation.canonical import strict_json_loads

INVENTORY_SCHEMA_VERSION = "evaluation-research-benchmark-inventory.v1"
_ROOT_FIELDS = frozenset({"schema_version", "benchmarks"})
_REQUIRED_BENCHMARK_FIELDS = frozenset(
    {
        "adapter_id",
        "name",
        "decision_unit",
        "action_space",
        "method_id",
        "status",
        "native_parity",
        "evidence_ceiling",
        "execution_owner",
        "input_schema",
        "export_schema",
        "applicable_tracks",
        "import_tracks",
        "produced_metric_ids",
        "required_artifact_ids",
        "analysis_plan_id",
        "analysis_unit",
        "curve_domain",
        "source_revision",
    }
)
_OPTIONAL_BENCHMARK_FIELDS = frozenset({"dataset_revision"})


def _load_inventory() -> tuple[Mapping[str, Any], ...]:
    try:
        document = strict_json_loads(
            files("cli.evaluation")
            .joinpath("golden/research_benchmark_inventory.v1.json")
            .read_bytes()
        )
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        raise RuntimeError(f"read research benchmark inventory: {exc}") from exc
    if (
        not isinstance(document, dict)
        or set(document) != _ROOT_FIELDS
        or document.get("schema_version") != INVENTORY_SCHEMA_VERSION
        or not isinstance(document.get("benchmarks"), list)
    ):
        raise RuntimeError("research benchmark inventory has an invalid envelope")
    benchmarks = tuple(document["benchmarks"])
    ids = {item.get("adapter_id") for item in benchmarks if isinstance(item, dict)}
    registered_by_id = {
        adapter.id: adapter for adapter in get_benchmark_registry().adapters
    }
    registered_ids = set(registered_by_id)
    if len(benchmarks) != len(ids) or ids != registered_ids:
        raise RuntimeError("research benchmark inventory and adapter registry differ")
    for item in benchmarks:
        if (
            not isinstance(item, dict)
            or not isinstance(item.get("import_tracks"), list)
            or not _REQUIRED_BENCHMARK_FIELDS.issubset(item)
            or not set(item).issubset(
                _REQUIRED_BENCHMARK_FIELDS | _OPTIONAL_BENCHMARK_FIELDS
            )
        ):
            raise RuntimeError(
                "research benchmark inventory has an invalid benchmark entry"
            )
        if any(
            not isinstance(item.get(field), str)
            or not item[field]
            or item[field] != item[field].strip()
            for field in ("analysis_plan_id", "analysis_unit")
        ) or item.get("curve_domain") not in {"not_applicable", "shared_budget"}:
            raise RuntimeError(
                "research benchmark inventory has an invalid analysis plan"
            )
        if (
            item.get("status") == "native-qualified"
            or item.get("native_parity") == "native"
            or item.get("evidence_ceiling") != "E0"
        ):
            raise RuntimeError(
                "research benchmark inventory overstates unqualified evidence"
            )
        if item.get("status") == "blocked" and item["import_tracks"]:
            raise RuntimeError("blocked research benchmark advertises an import track")
        adapter = registered_by_id[item["adapter_id"]]
        if (
            item["source_revision"] != adapter.source_revision
            or item.get("dataset_revision") != adapter.dataset_revision
            or item["decision_unit"] != adapter.decision_unit
            or item["action_space"] != adapter.action_space
            or tuple(item["applicable_tracks"]) != adapter.track_ids
        ):
            raise RuntimeError(
                "research benchmark inventory and adapter registry metadata differ"
            )
    return tuple(
        MappingProxyType(
            {
                key: tuple(value) if isinstance(value, list) else value
                for key, value in item.items()
            }
        )
        for item in benchmarks
    )


RESEARCH_BENCHMARKS = _load_inventory()
RESEARCH_BENCHMARKS_BY_ADAPTER = MappingProxyType(
    {item["adapter_id"]: item for item in RESEARCH_BENCHMARKS}
)
