"""Domain packs for F3 ``hs1_unmet_condition`` (project-authored template vocabulary).

A pack supplies one domain's nouns, value ranges, documents, roles, categories,
case narrative sentences and questions; ``f3_unmet`` owns the generic rule
frames and clause shapes. The re-check parser reads the same vocabulary, so no
vocabulary item of a pack may contain another and filler sentences never
mention one (``f3_unmet.validate_pack`` enforces both).

Quantity entries are ``measure`` ("a {noun} of {value}") or ``count``
("{n} {unit}"); thresholds are drawn from ``lo..hi`` in ``step`` units of the
natural value. Category ``swap`` sentences mention both categories and are the
only ones used when the category is the designated twin attribute.
"""

from __future__ import annotations

from typing import Any


def _m(
    key: str,
    kind: str,
    label: str,
    noun: str,
    fmt: str,
    lo: float,
    hi: float,
    step: float,
    unit: str = "",
) -> dict[str, Any]:
    return {
        "key": key,
        "kind": kind,
        "label": label,
        "style": "measure",
        "noun": noun,
        "fmt": fmt,
        "unit": unit,
        "lo": lo,
        "hi": hi,
        "step": step,
        "head": "",
    }


def _c(
    key: str,
    kind: str,
    label: str,
    unit: str,
    lo: int,
    hi: int,
    step: int = 1,
    head: str = "",
) -> dict[str, Any]:
    return {
        "key": key,
        "kind": kind,
        "label": label,
        "style": "count",
        "noun": unit,
        "fmt": "int",
        "unit": unit,
        "lo": lo,
        "hi": hi,
        "step": step,
        "head": head,
    }


