"""Source registry of the Omni multimodal decision corpus.

Every candidate source has a pinned origin, a licence verified from the dataset card or the upstream
terms, the skills it serves, its overlap risk with the eleven Vision-board benchmarks (and their
private sets), and a decision: ``train``, ``exclude`` or ``eval-only``. Training needs a permissive
licence (``PERMISSIVE``); NC, ND, share-alike, research-only, GPL and unknown licences never train
(``omni/SPEC.md``). Generators are our own code; their third-party inputs are listed as sources.

    python -m d25.omni.data.sources            # table
    python -m d25.omni.data.sources --json     # machine-readable
"""

from __future__ import annotations

import argparse
import json
from dataclasses import asdict, dataclass

