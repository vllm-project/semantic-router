BY_ID = {source.id: source for source in SOURCES}


def identities(source_id: str) -> list[str]:
    """Names under which holdout lists may refer to a registry source."""
    source = BY_ID[source_id]
    names = [source.id, *source.aliases]
    if source.origin.startswith("hf:"):
        names.append(source.origin[3:].split(" ")[0])
    return names


def check() -> None:
    ids = [source.id for source in SOURCES]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate source ids")
    for source in SOURCES:
        if source.decision not in {"train", "exclude", "eval-only"}:
            raise ValueError(f"{source.id}: bad decision {source.decision}")
        if source.decision == "train" and source.licence not in PERMISSIVE:
            raise ValueError(f"{source.id}: licence {source.licence} cannot train")
        if any(skill not in SKILLS for skill in source.skills):
            raise ValueError(f"{source.id}: unknown skill")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Omni corpus source registry")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    check()
    if args.json:
        print(json.dumps([asdict(source) for source in SOURCES], indent=1))
        return
    for source in SOURCES:
        print(
            f"{source.decision:9} {source.id:26} {source.licence:20} {','.join(source.skills) or '-':30} "
            f"{source.reason}"
        )


if __name__ == "__main__":
    main()
