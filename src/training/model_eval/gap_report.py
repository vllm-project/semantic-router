"""Render a versioned quality gap report from measured baselines (#3197).

The report separates findings by what a maintainer would have to change to fix
them, because "the model is worse than we thought" and "the harness measured a
different model" call for different work:

    identity     the config and the evaluation registry name different artifacts
    coverage     an artifact is served but nothing measures it
    calibration  the reported score does not match observed accuracy
    threshold    the configured threshold buys little over answering everything
    quality      the artifact itself underperforms on held-out data

Usage:
    python src/training/model_eval/gap_report.py \\
        --baseline baseline/jailbreak/jailbreak_baseline.json \\
        --output baseline/gap-report.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

from artifact_inventory import (
    DEFAULT_CONFIG,
    load_config,
    ref_mismatches,
    registry_drift,
    served_artifacts,
    uncovered_artifacts,
)
from constants import MODEL_REGISTRY

REPORT_VERSION = "v1"

# A reported confidence this far from observed accuracy makes a configured
# threshold unusable as a reliability control.
ECE_BUDGET = 0.05
# Below this, raising the threshold trades coverage for almost no accuracy.
THRESHOLD_VALUE_BUDGET = 0.05
# A gap this small between two artifacts, in AUC or in accuracy, is not worth
# reporting as a finding.
ARTIFACT_DELTA_BUDGET = 0.01
# A per-label recall below this is a quality gap rather than a rounding detail.
MIN_LABEL_RECALL = 0.7
# A spread this wide between the best and worst slice means the aggregate hides one.
MAX_SLICE_SPREAD = 0.1
# Comparisons need at least two members to say anything.
MIN_COMPARISON_SIZE = 2
# A slice thinner than this moves by whole points on one row, so its spread
# against another slice says more about the split than about the artifact.
MIN_SLICE_ROWS = 30
# A gate that misses more unsafe rows than this is not doing its job at the
# threshold it is configured with.
MIN_GATE_RECALL = 0.7


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Render a Router Model gap report")
    parser.add_argument(
        "--baseline",
        type=Path,
        nargs="+",
        required=True,
        help="Baseline JSON files produced by quality_baseline.py",
    )
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args(argv)


def render(baselines: list[dict[str, Any]], config_path: Path) -> str:
    config = load_config(config_path)
    inventory = served_artifacts(config)

    lines: list[str] = [
        f"# Router Model quality baseline and gap report ({REPORT_VERSION})",
        "",
        "Generated by `src/training/model_eval/gap_report.py` from baselines",
        "produced by `src/training/model_eval/quality_baseline.py`. Every number",
        "below is reproducible from the provenance manifests written next to the",
        "baseline it came from.",
        "",
        "## Served artifact inventory",
        "",
        "Resolved from the maintained configuration, not from the evaluation",
        "registry.",
        "",
        "| Task | Served artifact | Threshold | Load sites |",
        "| --- | --- | --- | --- |",
    ]
    for task, artifact in sorted(inventory.items()):
        thresholds = ", ".join(f"{value:g}" for value in artifact.thresholds) or "none"
        lines.append(
            f"| {task} | `{artifact.artifact_name}` | {thresholds} | "
            f"{len(artifact.sites)} |"
        )

    lines += ["", "## Measured baselines", ""]
    if baselines:
        lines += [
            "| Task | Artifact | Served | Rows | Accuracy | Macro F1 | ECE | "
            "AUC | R@1%FPR | Unsafe recall | Safe recall |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        ]
        for baseline in baselines:
            metrics = baseline["metrics"]
            calibration = baseline["calibration"]
            artifact = baseline["artifact"]
            served = "yes" if artifact.get("is_served_artifact", True) else "no"
            auc, recall_at_budget, unsafe_recall, safe_recall = _gate_columns(baseline)
            lines.append(
                f"| {baseline['task']} | `{artifact['repo'].split('/')[-1]}` | "
                f"{served} | {metrics['rows']} | {metrics['accuracy']:.4f} | "
                f"{metrics['macro_f1']:.4f} | {calibration['ece']:.4f} | "
                f"{auc} | {recall_at_budget} | {unsafe_recall} | {safe_recall} |"
            )
        lines += [
            "",
            "AUC, R@1%FPR and the two recalls all read the score the router "
            "compares to its threshold, which is the probability mass on "
            "`positive_labels`. They are blank for a task that declares none, "
            "because an argmax classifier has no safe class. AUC and R@1%FPR fix "
            "no threshold, so they are the pair that compares two artifacts built "
            "to different threshold conventions. Safe recall is one minus the "
            "false-positive rate at the configured threshold.",
        ]
    else:
        lines.append("No baseline was supplied.")

    findings = _dedupe(_collect(baselines, config, inventory))
    lines += ["", "## Gaps", ""]
    if not findings:
        lines.append("No gap was found.")
    for category in (
        "identity",
        "runtime",
        "coverage",
        "calibration",
        "threshold",
        "quality",
    ):
        matching = [text for kind, text in findings if kind == category]
        if not matching:
            continue
        lines += [f"### {category.capitalize()}", ""]
        lines += [f"- {text}" for text in matching]
        lines.append("")

    lines += [
        "## Reproduction",
        "",
        "```",
        "python src/training/model_eval/quality_baseline.py \\",
        "    --task jailbreak --device cuda --output-dir baseline/jailbreak",
        "python -m provenance.cli validate baseline/jailbreak/manifests",
        "```",
        "",
    ]
    return "\n".join(lines)


def _dedupe(findings: list[tuple[str, str]]) -> list[tuple[str, str]]:
    """Keep the first occurrence of each finding, preserving order."""
    seen: set[tuple[str, str]] = set()
    unique: list[tuple[str, str]] = []
    for finding in findings:
        if finding in seen:
            continue
        seen.add(finding)
        unique.append(finding)
    return unique


def _collect(
    baselines: list[dict[str, Any]], config: dict[str, Any], inventory: dict[str, Any]
) -> list[tuple[str, str]]:
    findings: list[tuple[str, str]] = []
    findings += [("identity", text) for text in ref_mismatches(config)]
    findings += [
        ("identity", text) for text in registry_drift(inventory, MODEL_REGISTRY)
    ]
    findings += [("coverage", text) for text in uncovered_artifacts(config)]

    measured = {
        (baseline["task"], baseline["artifact"]["repo"]): baseline
        for baseline in baselines
    }
    for task in sorted(inventory):
        if not any(key[0] == task for key in measured):
            findings.append(
                ("coverage", f"{task}: no baseline has been measured for this task")
            )

    for baseline in baselines:
        findings += _baseline_findings(baseline)
        if baseline["dataset"].get("split_rule") == "predefined":
            findings.append(
                (
                    "coverage",
                    f"{baseline['task']}: measured on "
                    f"`{baseline['dataset']['repo']}:{baseline['dataset']['split']}`, "
                    "the split the upstream publishes. That measures fit on the "
                    "distribution the artifact was trained on, not generalisation. "
                    "A by_source held-out set is still needed",
                )
            )
    findings += _runtime_findings(baselines)

    # A served artifact and an unserved one measured on the same split is the
    # comparison that separates an identity gap from a quality gap.
    for task in sorted({baseline["task"] for baseline in baselines}):
        served = [
            baseline
            for baseline in baselines
            if baseline["task"] == task
            and baseline["artifact"].get("is_served_artifact", True)
        ]
        others = [
            baseline
            for baseline in baselines
            if baseline["task"] == task
            and not baseline["artifact"].get("is_served_artifact", True)
        ]
        for current in served:
            for other in others:
                finding = _comparison_finding(task, current, other)
                if finding is not None:
                    findings.append(finding)
    return findings


def _comparison_finding(
    task: str, current: dict[str, Any], other: dict[str, Any]
) -> tuple[str, str] | None:
    """Compare a candidate against the served artifact on the same split.

    Accuracy moves with the threshold and with how many positives the split
    carries, so it cannot rank two artifacts that were built to different
    threshold conventions. Where both carry a threshold-free separation, that is
    what decides. Accuracy is the fallback for a task with no positive labels,
    where the decision really is the argmax.
    """
    name = other["artifact"]["repo"].split("/")[-1]
    mine = current.get("discrimination")
    theirs = other.get("discrimination")
    if mine and theirs:
        delta = theirs["roc_auc"] - mine["roc_auc"]
        if delta <= ARTIFACT_DELTA_BUDGET:
            return None
        return (
            "identity",
            f"{task}: the unserved `{name}` separates the positive class at AUC "
            f"{theirs['roc_auc']:.4f} on the same split against "
            f"{mine['roc_auc']:.4f} for the served artifact, a {delta:.4f} gap. "
            "Neither number fixes a threshold, so retuning the configured one "
            "does not close it",
        )
    delta = other["metrics"]["accuracy"] - current["metrics"]["accuracy"]
    if delta <= ARTIFACT_DELTA_BUDGET:
        return None
    return (
        "identity",
        f"{task}: the unserved `{name}` scores "
        f"{other['metrics']['accuracy']:.4f} on the same split against "
        f"{current['metrics']['accuracy']:.4f} for the served artifact, a "
        f"{delta:.4f} gap. The harness reports the better number while the "
        "router serves the worse artifact",
    )


def _runtime_findings(baselines: list[dict[str, Any]]) -> list[tuple[str, str]]:
    """Flag an artifact whose runtime requirements differ from the rest of the set.

    Every served artifact is loaded by the same process, so one artifact that
    needs a newer library than its siblings makes the whole portfolio
    unloadable on the older one.
    """
    served = [
        baseline
        for baseline in baselines
        if baseline["artifact"].get("is_served_artifact", True)
        and baseline["artifact"].get("tokenizer_class")
    ]
    if len(served) < MIN_COMPARISON_SIZE:
        return []
    counts: dict[str, list[str]] = {}
    for baseline in served:
        counts.setdefault(baseline["artifact"]["tokenizer_class"], []).append(
            baseline["artifact"]["repo"].split("/")[-1]
        )
    if len(counts) < MIN_COMPARISON_SIZE:
        return []
    majority = max(counts.items(), key=lambda item: len(item[1]))
    return [
        (
            "runtime",
            f"`{name}` declares tokenizer class `{declared}` while "
            f"{len(majority[1])} sibling artifacts declare `{majority[0]}`; the "
            "portfolio has no single runtime that loads all of it",
        )
        for declared, names in sorted(counts.items())
        if declared != majority[0]
        for name in names
    ]


def _gate_columns(baseline: dict[str, Any]) -> tuple[str, str, str, str]:
    """The four gate cells of the summary row: AUC, R@budget, unsafe, safe.

    All four read the score the router compares to its threshold, so a task that
    declares no positive labels leaves all four blank. AUC and the recall at the
    false-positive budget fix no threshold. The two recalls are read at the
    configured one, and safe class recall is one minus the false-positive rate.
    """
    separation = baseline.get("discrimination") or {}

    points = {
        point["threshold"]: point
        for point in baseline["abstention"].get("operating_points") or []
    }
    unsafe = safe = None
    for threshold in baseline["artifact"].get("configured_thresholds") or []:
        point = points.get(threshold)
        if point is None:
            continue
        unsafe = point["recall"]
        if point["false_positive_rate"] is not None:
            safe = 1 - point["false_positive_rate"]
        break

    cells = (
        separation.get("roc_auc"),
        separation.get("recall_at_fpr_budget"),
        unsafe,
        safe,
    )
    rendered = ["" if value is None else f"{value:.4f}" for value in cells]
    return rendered[0], rendered[1], rendered[2], rendered[3]


def _threshold_findings(
    baseline: dict[str, Any], task: str, name: str
) -> list[tuple[str, str]]:
    """Judge each configured threshold on the score the router compares to it.

    A gate artifact declares ``positive_labels``, and the router thresholds the
    probability mass on those classes. For everything else the decision is an
    argmax, and the abstention curve is the right reading.
    """
    findings: list[tuple[str, str]] = []
    points = {
        point["threshold"]: point
        for point in baseline["abstention"].get("operating_points") or []
    }
    curve = {point["threshold"]: point for point in baseline["abstention"]["curve"]}
    open_gate = curve.get(0.0)

    for threshold in baseline["artifact"].get("configured_thresholds", []):
        point = points.get(threshold)
        if point is not None:
            if point["recall"] is None or point["false_positive_rate"] is None:
                continue
            if point["recall"] < MIN_GATE_RECALL:
                labels = ", ".join(f"`{label}`" for label in point["positive_labels"])
                findings.append(
                    (
                        "threshold",
                        f"{task}: on `{name}`, the configured threshold "
                        f"{threshold:g} on P({labels}) catches "
                        f"{point['recall']:.1%} of unsafe rows while flagging "
                        f"{point['false_positive_rate']:.1%} of safe ones. Safe "
                        f"class recall is {1 - point['false_positive_rate']:.1%}",
                    )
                )
            continue

        gate = curve.get(threshold)
        if gate is None or open_gate is None or gate["selective_accuracy"] is None:
            continue
        gain = gate["selective_accuracy"] - open_gate["selective_accuracy"]
        if gain < THRESHOLD_VALUE_BUDGET:
            findings.append(
                (
                    "threshold",
                    f"{task}: on `{name}`, gating on the argmax score at the "
                    f"configured threshold {threshold:g} drops "
                    f"{1 - gate['coverage']:.1%} of rows and raises accuracy by "
                    f"only {gain:+.4f}",
                )
            )
    return findings


def _baseline_findings(baseline: dict[str, Any]) -> list[tuple[str, str]]:
    findings: list[tuple[str, str]] = []
    task = baseline["task"]
    name = baseline["artifact"]["repo"].split("/")[-1]
    calibration = baseline["calibration"]

    findings += [
        ("identity", text)
        for text in baseline.get("gaps", [])
        if "different order than the artifact" in text
        or "do not match the artifact labels" in text
    ]

    if calibration["ece"] > ECE_BUDGET:
        findings.append(
            (
                "calibration",
                f"{task}: `{name}` has ECE {calibration['ece']:.4f} and MCE "
                f"{calibration['mce']:.4f}, above the {ECE_BUDGET:.2f} budget; a "
                "configured threshold does not mean what its value suggests",
            )
        )

    findings += _threshold_findings(baseline, task, name)

    worst = min(
        baseline["metrics"]["per_label"].items(),
        key=lambda item: item[1]["recall"],
        default=None,
    )
    if worst is not None and worst[1]["recall"] < MIN_LABEL_RECALL:
        findings.append(
            (
                "quality",
                f"{task}: `{name}` recalls only {worst[1]['recall']:.1%} of "
                f"`{worst[0]}` rows at precision {worst[1]['precision']:.3f}",
            )
        )

    slices = [
        entry for entry in baseline.get("slices", []) if entry["rows"] >= MIN_SLICE_ROWS
    ]
    if len(slices) >= MIN_COMPARISON_SIZE:
        best = max(slices, key=lambda entry: entry["accuracy"])
        weakest = min(slices, key=lambda entry: entry["accuracy"])
        if best["accuracy"] - weakest["accuracy"] > MAX_SLICE_SPREAD:
            findings.append(
                (
                    "quality",
                    f"{task}: `{name}` accuracy spans {weakest['accuracy']:.4f} on "
                    f"`{weakest['name']}` to {best['accuracy']:.4f} on "
                    f"`{best['name']}`; the aggregate hides the weak slice",
                )
            )
    return findings


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    baselines = [json.loads(path.read_text(encoding="utf-8")) for path in args.baseline]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(baselines, args.config), encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
